// Builds src/data/rgaa-map.js from the official RGAA 4.1 criteria file
// (DISIC/RGAA, v4.1/JSON/criteres.json, Licence Ouverte 2.0 / Etalab,
// https://github.com/DISIC/RGAA). Maps WCAG 2.1 success criteria to RGAA criteria.
import { readFileSync, writeFileSync } from 'node:fs';
const src = JSON.parse(readFileSync(new URL('./rgaa-4.1-criteres.json', import.meta.url)));
const map = {};
const titles = {};
for (const topic of src.topics) {
  for (const { criterium: c } of topic.criteria) {
    const id = `${topic.number}.${c.number}`;
    titles[id] = c.title.replace(/\[([^\]]+)\]\([^)]+\)/g, '$1').replace(/`/g, '');
    for (const ref of c.references || []) {
      for (const w of ref.wcag || []) {
        const m = w.match(/\/\s*(\d+\.\d+\.\d+)/);
        if (!m) continue;
        (map[m[1]] ||= []).includes(id) || map[m[1]].push(id);
      }
    }
  }
}
const out = `// GENERATED by scripts/build-rgaa-map.mjs - do not edit.
// Source: RGAA 4.1, DISIC/RGAA v4.1/JSON/criteres.json (Licence Ouverte 2.0).
export const WCAG_TO_RGAA = ${JSON.stringify(map, null, 0)};
export const RGAA_TITLES = ${JSON.stringify(titles, null, 0)};
`;
writeFileSync(new URL('../src/data/rgaa-map.js', import.meta.url), out);
console.log(Object.keys(map).length, 'WCAG SC mapped;', Object.keys(titles).length, 'RGAA criteria');
